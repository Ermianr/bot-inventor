//! Load and save of the `.botproj` folder.

use std::collections::BTreeMap;
use std::fs::{self, File, OpenOptions};
use std::io::{Read, Write};
use std::path::{Path, PathBuf};

use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::Value;

use crate::error::ProjectError;
use crate::migrate::{self, RawProject};
use crate::model::{CURRENT_FORMAT_VERSION, Flow, Project};
use crate::names::FlowName;

/// The manifest, at the root of the project folder.
pub const MANIFEST_FILE: &str = "bot.botproj";
/// The folder with one file per flow.
pub const FLOWS_DIR: &str = "flows";
/// The ending of a flow file; the flow name is the rest of the file name.
pub const FLOW_SUFFIX: &str = ".flow.json";
/// The file that keeps local state and the token out of git.
pub const GITIGNORE_FILE: &str = ".gitignore";
/// A file larger than this is refused before it is read in full.
pub const MAX_FILE_BYTES: u64 = 4 * 1024 * 1024;
/// A project with more flows than this is refused.
pub const MAX_FLOWS: usize = 256;

const GITIGNORE_CONTENT: &str = "# Generated by Bot Inventor.\n.env\n.botinventor/\n";

/// A loaded project, and the format version it was written in when that was older
/// than the current one (the project in memory is always in the current version).
#[derive(Debug, Clone, PartialEq)]
pub struct Loaded {
    pub project: Project,
    pub migrated_from: Option<u32>,
}

impl Project {
    /// Reads the project in `dir`: `bot.botproj` and every `flows/*.flow.json`.
    ///
    /// Nothing is written. Symbolic links, files that are not regular, files over
    /// [`MAX_FILE_BYTES`] and more than [`MAX_FLOWS`] flows are refused. Only the shape
    /// of the files is checked; the graph is checked when it is compiled.
    ///
    /// # Errors
    ///
    /// Returns a [`ProjectError`] that names the file that could not be read or parsed.
    pub fn load(dir: &Path) -> Result<Loaded, ProjectError> {
        let manifest_path = dir.join(MANIFEST_FILE);
        let manifest_text = match read_text(&manifest_path) {
            Err(ProjectError::Io { source, .. })
                if source.kind() == std::io::ErrorKind::NotFound =>
            {
                return Err(ProjectError::MissingManifest {
                    path: manifest_path,
                });
            }
            other => other?,
        };
        let version = read_version(&manifest_path, &manifest_text)?;

        let mut flow_texts = Vec::new();
        for (name, path) in scan_flows(&dir.join(FLOWS_DIR))? {
            let text = read_text(&path)?;
            flow_texts.push((name, path, text));
        }

        if version == CURRENT_FORMAT_VERSION {
            let manifest = parse(&manifest_path, &manifest_text)?;
            let mut flows = BTreeMap::new();
            for (name, path, text) in &flow_texts {
                flows.insert(name.clone(), parse::<Flow>(path, text)?);
            }
            return Ok(Loaded {
                project: Project { manifest, flows },
                migrated_from: None,
            });
        }

        let mut raw = RawProject {
            manifest: parse(&manifest_path, &manifest_text)?,
            flows: BTreeMap::new(),
        };
        for (name, path, text) in &flow_texts {
            raw.flows
                .insert(name.as_str().to_owned(), parse::<Value>(path, text)?);
        }
        migrate::migrate(&mut raw, version);
        let manifest = from_value(&manifest_path, raw.manifest)?;
        let mut flows = BTreeMap::new();
        for (name, path, _) in flow_texts {
            let value = raw.flows.remove(name.as_str()).unwrap_or(Value::Null);
            flows.insert(name, from_value::<Flow>(&path, value)?);
        }
        Ok(Loaded {
            project: Project { manifest, flows },
            migrated_from: Some(version),
        })
    }

    /// Writes the project to `dir`, creating it if needed.
    ///
    /// Every file goes through a temporary file in its own folder and a rename, with a
    /// stable key order. The `.gitignore` is created only if it does not exist. Flow
    /// files of flows that are no longer in the project are removed. `.env`, `assets/`
    /// and `.botinventor/` are never touched.
    ///
    /// # Errors
    ///
    /// Returns a [`ProjectError`] if the project cannot be loaded back (a version that
    /// is not the current one, a position that is not finite, a file over the limit or
    /// too many flows) or a file cannot be written. Nothing is written in the first
    /// cases.
    pub fn save(&self, dir: &Path) -> Result<(), ProjectError> {
        if self.manifest.format_version != CURRENT_FORMAT_VERSION {
            return Err(ProjectError::UnsavableVersion {
                found: self.manifest.format_version,
                supported: CURRENT_FORMAT_VERSION,
            });
        }
        if self.flows.len() > MAX_FLOWS {
            return Err(ProjectError::TooManyFlows {
                count: self.flows.len(),
                limit: MAX_FLOWS,
            });
        }

        let flows_dir = dir.join(FLOWS_DIR);
        let manifest_path = dir.join(MANIFEST_FILE);
        let mut files = vec![(
            manifest_path.clone(),
            render(&manifest_path, &self.manifest)?,
        )];
        for (name, flow) in &self.flows {
            if let Some(node) = flow
                .nodes
                .iter()
                .find(|n| !n.editor.x.is_finite() || !n.editor.y.is_finite())
            {
                return Err(ProjectError::NonFinitePosition {
                    flow: name.to_string(),
                    node: node.id.to_string(),
                });
            }
            let path = flows_dir.join(format!("{name}{FLOW_SUFFIX}"));
            let text = render(&path, flow)?;
            files.push((path, text));
        }
        for (path, text) in &files {
            if u64::try_from(text.len()).map_or(true, |len| len > MAX_FILE_BYTES) {
                return Err(ProjectError::TooLarge {
                    path: path.clone(),
                    limit: MAX_FILE_BYTES,
                });
            }
        }

        create_dir(dir)?;
        match fs::symlink_metadata(&flows_dir) {
            Ok(meta) if meta.file_type().is_symlink() => {
                return Err(ProjectError::Symlink { path: flows_dir });
            }
            Ok(meta) if !meta.is_dir() => {
                return Err(ProjectError::NotAFolder { path: flows_dir });
            }
            Ok(_) => {}
            Err(source) if source.kind() == std::io::ErrorKind::NotFound => {
                create_dir(&flows_dir)?;
            }
            Err(source) => {
                return Err(ProjectError::Io {
                    path: flows_dir,
                    source,
                });
            }
        }

        for (path, text) in &files {
            write_atomic(path, text.as_bytes())?;
        }
        let gitignore = dir.join(GITIGNORE_FILE);
        if fs::symlink_metadata(&gitignore).is_err() {
            write_atomic(&gitignore, GITIGNORE_CONTENT.as_bytes())?;
        }
        self.remove_stale_flows(&flows_dir)
    }

    fn remove_stale_flows(&self, flows_dir: &Path) -> Result<(), ProjectError> {
        let entries = fs::read_dir(flows_dir).map_err(|source| io_error(flows_dir, source))?;
        for entry in entries {
            let entry = entry.map_err(|source| io_error(flows_dir, source))?;
            let file_name = entry.file_name();
            let Some(stem) = file_name.to_str().and_then(|n| n.strip_suffix(FLOW_SUFFIX)) else {
                continue;
            };
            // Only files that this crate could have written: a name it would refuse
            // belongs to somebody else.
            let Ok(name) = FlowName::parse(stem) else {
                continue;
            };
            let is_dir = entry.file_type().is_ok_and(|t| t.is_dir());
            if !is_dir && !self.flows.contains_key(&name) {
                let path = entry.path();
                fs::remove_file(&path).map_err(|source| io_error(&path, source))?;
            }
        }
        Ok(())
    }
}

fn io_error(path: &Path, source: std::io::Error) -> ProjectError {
    ProjectError::Io {
        path: path.to_path_buf(),
        source,
    }
}

fn regular_file(path: &Path) -> Result<fs::Metadata, ProjectError> {
    let meta = fs::symlink_metadata(path).map_err(|source| io_error(path, source))?;
    if meta.file_type().is_symlink() {
        return Err(ProjectError::Symlink {
            path: path.to_path_buf(),
        });
    }
    if !meta.is_file() {
        return Err(ProjectError::NotAFile {
            path: path.to_path_buf(),
        });
    }
    Ok(meta)
}

fn too_large(path: &Path) -> ProjectError {
    ProjectError::TooLarge {
        path: path.to_path_buf(),
        limit: MAX_FILE_BYTES,
    }
}

fn read_text(path: &Path) -> Result<String, ProjectError> {
    if regular_file(path)?.len() > MAX_FILE_BYTES {
        return Err(too_large(path));
    }
    let file = File::open(path).map_err(|source| io_error(path, source))?;
    let mut bytes = Vec::new();
    // The file may have grown since the check above.
    file.take(MAX_FILE_BYTES + 1)
        .read_to_end(&mut bytes)
        .map_err(|source| io_error(path, source))?;
    if u64::try_from(bytes.len()).map_or(true, |len| len > MAX_FILE_BYTES) {
        return Err(too_large(path));
    }
    String::from_utf8(bytes).map_err(|_| ProjectError::NotUtf8 {
        path: path.to_path_buf(),
    })
}

fn parse<T: DeserializeOwned>(path: &Path, text: &str) -> Result<T, ProjectError> {
    serde_json::from_str(text).map_err(|source| ProjectError::Json {
        path: path.to_path_buf(),
        source,
    })
}

fn from_value<T: DeserializeOwned>(path: &Path, value: Value) -> Result<T, ProjectError> {
    serde_json::from_value(value).map_err(|source| ProjectError::Json {
        path: path.to_path_buf(),
        source,
    })
}

/// Reads `format_version` and checks it against the version this crate supports.
fn read_version(path: &Path, text: &str) -> Result<u32, ProjectError> {
    #[derive(serde::Deserialize)]
    struct Probe {
        format_version: Option<Value>,
    }
    let probe: Probe = parse(path, text)?;
    let invalid = || ProjectError::InvalidVersion {
        path: path.to_path_buf(),
    };
    let found = probe
        .format_version
        .as_ref()
        .and_then(Value::as_u64)
        .filter(|&n| n >= 1)
        .ok_or_else(invalid)?;
    let found = u32::try_from(found).unwrap_or(u32::MAX);
    if found > CURRENT_FORMAT_VERSION {
        return Err(ProjectError::NewerFormat {
            path: path.to_path_buf(),
            found,
            supported: CURRENT_FORMAT_VERSION,
        });
    }
    Ok(found)
}

/// The flow files in `dir` with the flow each one holds, in name order. A missing
/// folder is a project with no flows.
fn scan_flows(dir: &Path) -> Result<Vec<(FlowName, PathBuf)>, ProjectError> {
    match fs::symlink_metadata(dir) {
        Ok(meta) if meta.file_type().is_symlink() => {
            return Err(ProjectError::Symlink {
                path: dir.to_path_buf(),
            });
        }
        Ok(meta) if !meta.is_dir() => {
            return Err(ProjectError::NotAFolder {
                path: dir.to_path_buf(),
            });
        }
        Ok(_) => {}
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(source) => return Err(io_error(dir, source)),
    }

    let mut found = Vec::new();
    for entry in fs::read_dir(dir).map_err(|source| io_error(dir, source))? {
        let entry = entry.map_err(|source| io_error(dir, source))?;
        let file_name = entry.file_name();
        // Anything that does not end in `.flow.json` (a leftover `.tmp`, for example)
        // is not a flow.
        let Some(stem) = file_name.to_str().and_then(|n| n.strip_suffix(FLOW_SUFFIX)) else {
            continue;
        };
        let path = entry.path();
        let name = FlowName::parse(stem).map_err(|source| ProjectError::InvalidFlowFileName {
            path: path.clone(),
            source,
        })?;
        found.push((name, path));
    }
    if found.len() > MAX_FLOWS {
        return Err(ProjectError::TooManyFlows {
            count: found.len(),
            limit: MAX_FLOWS,
        });
    }
    found.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(found)
}

fn render<T: Serialize>(path: &Path, value: &T) -> Result<String, ProjectError> {
    let mut text = serde_json::to_string_pretty(value).map_err(|source| ProjectError::Json {
        path: path.to_path_buf(),
        source,
    })?;
    text.push('\n');
    Ok(text)
}

fn create_dir(path: &Path) -> Result<(), ProjectError> {
    fs::create_dir_all(path).map_err(|source| io_error(path, source))
}

/// Writes `bytes` to a new temporary file next to `path` and renames it over `path`,
/// so a reader never sees half a file.
fn write_atomic(path: &Path, bytes: &[u8]) -> Result<(), ProjectError> {
    let mut tmp_name = path.as_os_str().to_owned();
    tmp_name.push(".tmp");
    let tmp = PathBuf::from(tmp_name);

    // A leftover from a crash is removed; `create_new` then refuses to follow a link
    // that somebody placed at that name.
    match fs::remove_file(&tmp) {
        Ok(()) => {}
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => {}
        Err(source) => return Err(io_error(&tmp, source)),
    }
    let written = (|| {
        let mut file = OpenOptions::new().write(true).create_new(true).open(&tmp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
        fs::rename(&tmp, path)
    })();
    written.map_err(|source| {
        // Best effort: the error being reported is the one that matters.
        let _ = fs::remove_file(&tmp);
        io_error(path, source)
    })
}
